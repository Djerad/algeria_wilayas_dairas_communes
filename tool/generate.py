"""Generates lib/src/data.dart from tool/algeria_cities.json."""
import json, sys, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(root, 'tool', 'algeria_cities.json'), encoding='utf-8'))
def s(x): return "'" + str(x).strip().replace('\\', '\\\\').replace("'", "\\'") + "'"
w = {}
for r in d: w.setdefault(r['wilaya_code'], (r['wilaya_name_fr'], r['wilaya_name']))
rows = sorted(d, key=lambda r: (r['wilaya_code'], r['commune_name_fr']))
out = ["// GENERATED by tool/generate.py. Do not edit.",
       "// Data: github.com/ihahachi/algeria-cities (MIT).",
       "import 'models.dart';", "",
       "const List<Wilaya> kWilayas = ["]
for c in sorted(w):
    out.append(f"  Wilaya(code: {c}, name: {s(w[c][0])}, nameAr: {s(w[c][1])}),")
out += ["];", "", "const List<Commune> kCommunes = ["]
for r in rows:
    out.append(f"  Commune(id: {int(r['id'])}, wilayaCode: {r['wilaya_code']}, name: {s(r['commune_name_fr'])}, nameAr: {s(r['commune_name'])}, daira: {s(r['daira_name_fr'])}, dairaAr: {s(r['daira_name'])}, latitude: {float(r['Lat'])}, longitude: {float(r['Long'])}),")
out.append("];")
open(os.path.join(root, 'lib', 'src', 'data.dart'), 'w', encoding='utf-8').write("\n".join(out) + "\n")
print(len(w), "wilayas,", len(rows), "communes")
